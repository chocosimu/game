/// そのレベルの「レベル攻撃力」を返す。範囲外は端で止める。
int levelAttackFor(int level) {
  final i = (level - 1).clamp(0, levelAttackTable.length - 1);
  return levelAttackTable[i];
}

/// 累積経験値から「到達しているレベル」を返す（§1.1）。
/// 例：exp=0→Lv1、exp=10→Lv2、exp=39→Lv2、exp=40→Lv3。
int levelForExp(int exp) {
  var level = 1;
  for (var i = 1; i < cumulativeExpTable.length; i++) {
    if (exp >= cumulativeExpTable[i]) {
      level = i + 1;
    } else {
      break;
    }
  }
  return level;
}

/// 攻撃側の「基本攻撃力」を計算する（§1.6）。
/// 基本攻撃力 ＝ レベル攻撃力 ×{ 1 ＋（ちから ＋ 2×武器補正値）÷ 16 }
/// 武器を持っていなければ weaponBonus は 0。
double baseAttackPower(int levelAttack, int strength, {int weaponBonus = 0}) {
  return levelAttack * (1 + (strength + 2 * weaponBonus) / 16);
}

/// 守備側の防御力を反映した「基本ダメージ」（乱数を掛ける前の値）。§1.6。
/// 基本ダメージ ＝ 基本攻撃力 ×(35/36)^（守備側の防御力）
double baseDamage(double attackPower, int defense) {
  return attackPower * pow(35 / 36, defense);
}

/// 「基本ダメージ」に乱数(7/8〜9/8)を掛けて、実際に与えるダメージにする。§1.6。
/// 32段階の乱数（(112〜143)/128）。最低でも1ダメージは入る。
int rollDamage(double baseDamage, Random random) {
  final factor = (112 + random.nextInt(32)) / 128; // 7/8 〜 9/8
  final dmg = (baseDamage * factor).floor();
  return dmg < 1 ? 1 : dmg;
}

/// レベルアップ1回ぶんの最大HP上昇量を、乱数で決める（§1.2）。
/// 分布：+5＝1/3／+4・+6＝各2/9／+3・+7＝各1/9（平均ちょうど+5）。
int hpGrowth(Random random) {
  final r = random.nextInt(9); // 0〜8 の9通り
  if (r < 3) return 5; // 3/9
  if (r < 5) return 4; // 2/9
  if (r < 7) return 6; // 2/9
  if (r == 7) return 3; // 1/9
  return 7; // 1/9
}
